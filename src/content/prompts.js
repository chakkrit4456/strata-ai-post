import YAML from 'yaml';
import { slotLabel } from '../time.js';
import { getTone } from '../image/themes.js';

const MODE_TEXT = {
  promo: 'โปรโมทได้ (ใช้ราคา/ขอบเขตตามข้อมูลจริง ชวนทักมาคุยได้)',
  soft: 'ห้ามขาย: เขียนใหม่เป็นเนื้อหาให้ความรู้ที่เกี่ยวกับหัวข้อ ไม่มีราคา ไม่มีคำชวนจ้าง/ทักแชท',
  value: 'เนื้อหาให้ความรู้/สนุก ไม่มีราคา ไม่มีคำชวนจ้าง/ทักแชท',
};

// system prompt คงที่ทั้งวัน (cache ได้) — ข้อมูลที่เปลี่ยนไปอยู่ใน user prompt
export function systemPrompt(brand) {
  return `คุณคือคนเขียนคอนเทนต์ Facebook ให้ ${brand.studio} (แบรนด์ ${brand.name}) สตูดิโอรับทำเว็บ ระบบ Bot/Automation และซอฟต์แวร์ ตั้งอยู่ที่${brand.location}
เป้าหมาย: ให้คนในกลุ่ม IT/ธุรกิจในไทยรู้จักและไว้ใจแบรนด์ จนอยากจ้างงาน โดยไม่ทำให้ใครรู้สึกว่าโดนสแปม

ข้อเท็จจริงทั้งหมดที่ใช้ได้ (ห้ามแต่งเพิ่ม):
<brand>
${YAML.stringify(brand)}</brand>

กติกา:
- เขียนภาษาไทย ตัวตนของแบรนด์: ${brand.voice} (น้ำเสียงของแต่ละโพสต์กำหนดแยกให้ ให้ทำตามนั้น)
- ทุกโพสต์ต้องแตกต่างจากโพสต์ก่อนๆ อย่างชัดเจน ทั้งหัวข้อ มุมมอง วิธีเปิดเรื่อง และรูปแบบการเขียน ห้ามใช้สูตรเดิมซ้ำ
- ราคา ขอบเขต ระยะเวลา และผลงาน ใช้ได้เฉพาะจากข้อมูลข้างบน ห้ามแต่งตัวเลข โปรโมชัน ส่วนลด หรือของแถม
- เรียกแพ็กเกจด้วยชื่อภาษาไทยในช่อง name เท่านั้น (ห้ามใช้ id เช่น starter/backoffice/enterprise เป็นชื่อแพ็กเกจ)
- ห้ามบอกว่า "เคยทำ/พัฒนาให้" งานที่ไม่อยู่ใน portfolio ถ้าหัวข้อเป็นระบบที่ไม่อยู่ในผลงาน ให้เขียนแบบ "รับทำ/ทำได้" แทน
  และห้ามแต่งฟีเจอร์เฉพาะ (เช่น แจ้งเตือนผ่านแอปไหน) ว่าเป็นของผลงานจริง ถ้าไม่มีในข้อมูล
- ห้ามอ้างสิ่งในหัวข้อ doNotClaim (เช่น จำนวนลูกค้า รีวิว ชื่อลูกค้า)
- เนื้อหาเชิงเทคนิคต้องถูกต้อง ถ้าไม่แน่ใจให้เลือกเรื่องที่มั่นใจแทน
- แฮชแท็กรวมไม่เกิน 3 อัน ไม่ใช้ตัวพิมพ์ใหญ่ทั้งประโยค ไม่ใช้เครื่องหมาย !!! ซ้ำ
- ข้อความของแต่ละกลุ่มต้องเขียนใหม่ให้เข้ากับสมาชิกและกฎของกลุ่มนั้น ห้ามก็อปแคปชันเพจหรือของกลุ่มอื่น
  (เปิดเรื่องคนละแบบ ลำดับคนละแบบ) และต้องทำตามกฎของกลุ่มเคร่งครัด
- โพสต์แบบไม่ขาย (value/soft) ถ้ากลุ่มอนุญาตลายเซ็น ลงท้ายสั้นๆ ได้แค่ "— ${brand.name} dev" ห้ามใส่ลิงก์หรือชวนทัก
- ภาพ: ข้อความในภาพสั้น อ่านจบใน 3 วินาที headline ไม่เกิน 60 ตัวอักษร bullets ไม่เกิน 4 ข้อ
- ห้ามมีตัวอักษร emoji ในข้อมูลภาพทุกช่อง (ฟอนต์ในภาพไม่รองรับ)
- headline ใส่ | ได้ 1 ครั้งเพื่อให้ส่วนท้ายเป็นสีเน้น เช่น "ระบบสต็อกที่|ไม่ต้องนับมือ"
- ข่าว: ใช้ได้เฉพาะข่าวในรายการที่ให้ สรุปด้วยภาษาของเราเอง ห้ามคัดลอกประโยคจากข่าว ห้ามแต่งรายละเอียดที่ข่าวไม่ได้บอก
  ต้องบอกชื่อแหล่งข่าวในแคปชัน (เช่น "ที่มา: Blognone") และใส่ลิงก์ข่าวในช่อง newsUrl ให้ตรงกับรายการทุกตัวอักษร
- visual: คำบรรยายภาพประกอบเป็นภาษาอังกฤษ 1 ประโยค เป็นฉากที่จับต้องได้ (อุปกรณ์ + สิ่งที่แสดงบนจอ + บรรยากาศ) ไม่ใช่แนวคิดนามธรรม
  เช่น ข่าวช่องโหว่ → "a laptop on a dark desk showing a red security alert dashboard with a glowing shield icon" ห้ามมีตัวอักษรหรือโลโก้ในภาพ`;
}

export function slotPrompt({ date, slotPlan, groups, recentTopics, topicHint = '', tone = '', news = [] }) {
  const p = slotPlan.pillar;
  const groupLines = slotPlan.groups.map(({ groupId, mode }) => {
    const g = groups.find((x) => x.id === groupId);
    return `- groupId: ${g.id}
  ชื่อ: ${g.name}
  สมาชิก: ${g.audience || '-'}
  กฎกลุ่ม: ${g.rules || '-'}
  โหมด: ${mode} — ${MODE_TEXT[mode]}
  ลายเซ็น: ${g.signature ? 'ได้' : 'ไม่ได้'}`;
  }).join('\n');
  const needsSoft = slotPlan.groups.some((g) => g.mode === 'soft');
  const t = getTone(tone);
  const mustNews = p.template === 'news';
  const newsLines = news
    .map((n, i) => `${i + 1}. [${n.source}] ${n.title}\n   ${n.url}${n.summary ? `\n   ${n.summary.slice(0, 140)}` : ''}`)
    .join('\n');
  let newsBlock = '';
  if (news.length) {
    newsBlock = `\nข่าวล่าสุด (${mustNews
      ? 'เลือก 1 ข่าวที่เกี่ยวกับธุรกิจ/IT ในไทยมากที่สุด แล้วเขียนจากข่าวนั้น'
      : 'ไม่บังคับ: ถ้ามีข่าวที่เข้ากับหัวข้อ หยิบมาเชื่อมให้ทันเหตุการณ์ได้'}):\n${newsLines}\n`;
  } else if (mustNews) {
    newsBlock = '\nข่าวล่าสุด: (ไม่มี) — เขียนเรื่องเทรนด์เทคโนโลยีที่มั่นใจว่าถูกต้อง และใส่ newsUrl เป็น ""\n';
  }

  return `วันที่ ${date} ${slotLabel(slotPlan.slot)}
หมวด: ${p.label} (${slotPlan.isPromo ? 'โพสต์โปรโมท' : 'โพสต์ให้ความรู้/สนุก ห้ามขาย'})
แนวทาง: ${p.brief}${topicHint ? `
หัวข้อที่เจ้าของเพจอยากให้เขียน: ${topicHint}
(ยึดหัวข้อนี้เป็นหลัก แต่ข้อเท็จจริงทั้งหมดยังต้องมาจากข้อมูลแบรนด์เท่านั้น)` : ""}
เทมเพลตภาพหลัก: ${p.template}
น้ำเสียงของโพสต์นี้: ${t.name} — ${t.brief}
${newsBlock}
หัวข้อที่เคยโพสต์แล้ว (ห้ามซ้ำหรือคล้าย):
${recentTopics.length ? recentTopics.map((t) => `- ${t}`).join('\n') : '- (ยังไม่มี)'}

สิ่งที่ต้องส่งกลับ:
1. topic: หัวข้อใหม่ 1 บรรทัด
2. caption: แคปชันโพสต์เพจ 300–1200 ตัวอักษร${slotPlan.isPromo ? ' จบด้วยชวนทักแชทเพจเพื่อประเมินราคาฟรี' : ' จบด้วยคำถามชวนคอมเมนต์'}
3. hashtags: 0–3 อัน (รวมกับที่อยู่ใน caption แล้วต้องไม่เกิน 3)
4. image: ข้อมูลสำหรับเทมเพลต "${p.template}"
   - kicker: ป้ายสั้นภาษาอังกฤษตัวพิมพ์ใหญ่ เช่น DEV TIP, REAL TALK, PROJECT, PACKAGE, POLL
   - headline, subhead
   - bullets: 0–4 ข้อ (tip/showcase/package ใช้), question ให้ใส่ใน options แทน
   - code: โค้ด/คำสั่งไม่เกิน 6 บรรทัด (เฉพาะ tip ที่เหมาะ) ไม่มีให้ใส่ ""
   - options: ตัวเลือกโพล 2–4 ข้อ (เฉพาะ question) ไม่มีให้ใส่ []
   - cta: ข้อความท้ายภาพสั้นๆ
   - packageId: แพ็กเกจที่พูดถึง (starter/backoffice/enterprise) หรือ all; ถ้าไม่ใช่เทมเพลต package ใส่ all
   - source: ชื่อแหล่งข่าว (เฉพาะเมื่อใช้ข่าว) ไม่มีใส่ ""
   - visual: คำบรรยายภาพประกอบภาษาอังกฤษ 1 ประโยค เป็นฉากอุปกรณ์/วัตถุจริงที่เข้ากับเนื้อหาโพสต์นี้${p.template === 'fact' ? `
   เกล็ดความรู้ (ภาพ "รู้หรือไม่?"):
   - kicker: หมวดความรู้ภาษาอังกฤษสั้นๆ เช่น "WEB BASICS", "DEV HISTORY", "CAREER", "SECURITY"
   - headline: ข้อเท็จจริงที่น่าทึ่งใน 1 ประโยค (ไม่เกิน 60 ตัวอักษร)
   - subhead: อธิบายสั้นๆ ว่าทำไม/เป็นอย่างไร
   - bullets: 2–3 ข้อ ขยายความหรือเอาไปใช้ได้อย่างไร
   - ข้อเท็จจริงทุกข้อต้องถูกต้องและตรวจสอบได้ ถ้าไม่แน่ใจตัวเลข/ปี ให้เลือกเรื่องอื่น
   - ห้ามใส่ตัวเลขเคลมผลลัพธ์ลอยๆ เช่น "เร็วขึ้น 10 เท่า" "ลดต้นทุน 50%" ให้ใช้คำอย่าง "เร็วขึ้นมาก" แทน (ยกเว้นตัวเลขที่เป็นข้อเท็จจริงทั่วไป เช่น ปีที่เกิด, เลขพอร์ต)` : ''}${p.template === 'news' ? `
   ข่าว: kicker เช่น "TECH UPDATE", "NEW TOOL", "AI NEWS" · headline = สิ่งที่ใหม่ (ชื่อเครื่องมือ/อัปเดต) · bullets = ใหม่ตรงไหน / ใครควรสนใจ / ใช้ทำอะไรได้` : ''}${p.template === 'banner' ? `
   แบนเนอร์ (ภาพแนวนอนแบบป้ายโฆษณา บอกว่าเราคือใคร/ทำอะไรได้):
   - kicker: ชื่อแบรนด์หรือชื่อเรียกบริการภาษาอังกฤษสั้นๆ เช่น "STRATA STUDIO", "SMART STOCK"
   - headline: ชื่อบริการ/ระบบแบบจำง่าย (ไทยหรืออังกฤษ ไม่เกิน 30 ตัวอักษร) ใส่ | เพื่อขึ้นบรรทัดใหม่เป็นคำโปรยได้ เช่น "Smart Stock|ระบบสต็อกที่รู้ทุกการเคลื่อนไหว"
   - subhead: คำคมสั้นๆ ในเครื่องหมายคำพูด เช่น "จากร้านเล็ก สู่ระบบที่วัดผลได้"
   - bullets: 1 ข้อ = คำอธิบาย 1–2 บรรทัดว่าช่วยอะไร
   - features: ความสามารถหลัก 4 ข้อ {icon, title (2–4 คำ), desc (ไม่เกิน 30 ตัวอักษร)} จากข้อมูลจริงเท่านั้น
     icon เลือกจาก: shield, monitor, chart, report, cart, calendar, database, cloud, bot, code, phone, users, bell, lock, rocket, settings
   - slogan: ประโยคปิดท้ายแถบล่าง 1 ประโยค เช่น "จ้างทำระบบแล้วไม่ได้แค่ระบบ แต่ได้ข้อมูลกลับไปพัฒนาธุรกิจ"
   - tags: คำสั้น 2–3 คำ เช่น ["Web App", "Automation", "Support"]
   - visual: ภาพสินค้า/ระบบที่ใช้งานจริงในฉากธุรกิจ เช่น "a tablet showing a stock dashboard on a cafe counter", ไม่มีตัวอักษร` : ''}
5. softImage: ${needsSoft ? 'ภาพเทมเพลต tip แบบไม่ขาย (ไม่มีราคา/คำชวนจ้าง) สำหรับกลุ่มโหมด soft' : 'ไม่ใช้ ให้ใส่ค่าเหมือน image'}
6. variants: ข้อความ 150–1000 ตัวอักษรสำหรับทุกกลุ่มด้านล่าง กลุ่มละ 1 รายการ (groupId ต้องตรง)
7. newsUrl: ลิงก์ข่าวที่ใช้ (ต้องตรงกับรายการ) ถ้าไม่ได้ใช้ข่าวใส่ ""

กลุ่ม:
${groupLines || '- (ไม่มีกลุ่ม ให้ส่ง variants เป็น [])'}`;
}
